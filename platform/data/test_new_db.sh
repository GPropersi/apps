  nd myapp
  expect_rc "reserved list: $1 fails closed" 1
  expect_out_has "reserved list: $1 names the install command" "make host-data"
  expect_eq "reserved list: $1 makes no docker call" "$(docker_calls)" "0"
  expect_eq "reserved list: $1 writes no file" "$(find "$SECRETS" -mindepth 1 | wc -l)" "0"
}
l_absent() { rm -f "$RESERVED"; }
l_dir() { rm -f "$RESERVED"; mkdir "$RESERVED"; }
l_empty() { printf '# only comments\n\n' > "$RESERVED"; }
l_unreadable() { "$REAL_CHMOD" 000 "$RESERVED"; }
list_case "absent" l_absent
list_case "a directory" l_dir
list_case "no entries" l_empty
