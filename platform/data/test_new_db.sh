JOBS="$T_TMP/job-secrets"
LOCKS="$T_TMP/locks"
RESERVED="$T_TMP/reserved-names.txt"
LOGGER_LOG="$T_TMP/logger.log"
export STATE LOGGER_LOG

PGC=test-data-postgres
RDC=test-data-redis
PRE_PW='AbCdEfGhIjKlMnOpQrStUvWxYz0123456789abcd'

if command -v flock >/dev/null 2>&1; then _pass; else _fail "flock is available for the lock tests"; fi

# ---- stubs ----

mkstub() { # <name>: the body comes from stdin; the stub first logs "<name> <argv...>" to the call log
  local name="$1"
  {
    printf '#!/usr/bin/env bash\n'
    printf 'printf "%%s" %q >> "$CALL_LOG"\n' "$name"
    printf 'for a in "$@"; do printf " %%s" "$a" >> "$CALL_LOG"; done\n'
    printf 'printf "\\n" >> "$CALL_LOG"\n'
    cat
  } > "$STUB_BIN/$name"
  "$REAL_CHMOD" +x "$STUB_BIN/$name"
}

# logger records its message, not its option (the audit trail must carry no secret)
mkstub logger <<'EOF'
printf '%s\n' "$*" >> "$LOGGER_LOG"
exit 0
EOF

# new-db must never need these (secrets get their group from the setgid root); any call is logged and fails the case
mkstub chgrp <<'EOF'
exit 0
EOF
mkstub chown <<'EOF'
exit 0
EOF
export REAL_CHMOD
mkstub chmod <<'EOF'
exec "$REAL_CHMOD" "$@"
EOF

# docker: stateful. Failure switches are files $STATE/fail_<key> holding the exit code (124 = timeout); an
# $STATE/echo_<key> file makes the failure print the stdin text on stderr, as psql does for a syntax error.
# keys: pg-pre pg-role pg-database pg-grants pg-schema rd-pre rd-setuser rd-save; health: $STATE/fail_health_<name>.
mkstub docker <<'EOF'
S="$STATE"
sub="$1"
shift
stubreply() { [ ! -f "$S/reply_$1" ] || { cat "$S/reply_$1"; exit 0; }; }
stubfail() {
  [ -f "$S/fail_$1" ] || return 0
  [ ! -f "$S/echo_$1" ] || printf 'ERROR: failing statement: %s\n' "$input" >&2
  exit "$(cat "$S/fail_$1")"
}
case "$sub" in
  inspect)
    name="${*: -1}"
    [ ! -f "$S/fail_health_$name" ] || exit "$(cat "$S/fail_health_$name")"
    cat "$S/health_$name" 2>/dev/null || echo "running|healthy"
    exit 0 ;;
  exec)
    shift # -i
    name="$1"
    shift
    input="$(cat)"
    if [ "$1" = psql ]; then
      db=""
      prev=""
      for a in "$@"; do
        [ "$prev" != -d ] || db="$a"
        prev="$a"
      done
      printf '### psql db=%s\n%s\n' "$db" "$input" >> "$S/stdin.log"
      case "$input" in
        *"count(*) FROM pg_roles"*) key=pg-pre ;;
        *"CREATE ROLE"*) key=pg-role ;;
        *"CREATE DATABASE"*) key=pg-database ;;
        *"REVOKE CONNECT ON DATABASE postgres, template1"*) key=pg-grants ;;
        *"REVOKE ALL ON SCHEMA"*) key=pg-schema ;;
        *) echo "stub: unknown psql input" >&2; exit 97 ;;
      esac
      stubfail "$key"
      stubreply "$key"
      case "$key" in
        pg-pre)
          r="$(sed -n "s/.*rolname = '\([a-z0-9_]*\)'.*/\1/p" <<<"$input" | head -n 1)"
          n=0; [ ! -f "$S/role_$r" ] || n=1
          d=0; [ ! -f "$S/db_$r" ] || d=1
          echo "$n|$d" ;;
        pg-role)
          r="$(sed -n 's/.*CREATE ROLE "\([a-z0-9_]*\)".*/\1/p' <<<"$input" | head -n 1)"
          if [ ! -f "$S/role_$r" ]; then
            touch "$S/role_$r"
            sed -n "s/.*PASSWORD ''\([A-Za-z0-9]*\)'''.*/\1/p" <<<"$input" | head -n 1 > "$S/rolepw_$r"
            echo "$(( $(cat "$S/role_creates" 2>/dev/null || echo 0) + 1 ))" > "$S/role_creates"
          fi
          if grep -qF 'CONNECTION LIMIT 3;' <<<"$input"; then echo 3 > "$S/rolelimit_$r"; fi ;;
        pg-database)
          r="$(sed -n 's/.*CREATE DATABASE "\([a-z0-9_]*\)".*/\1/p' <<<"$input" | head -n 1)"
          touch "$S/db_$r" ;;
        pg-grants) touch "$S/grants_applied" ;;
        pg-schema) touch "$S/schema_$db" ;;
      esac
      exit 0
    fi
    # redis: sh -c <snippet> sh <admin file>, the command on stdin
    [ "$1 $2" = "sh -c" ] || { echo "stub: unexpected redis argv" >&2; exit 98; }
    printf '### redis\n%s\n' "$input" >> "$S/stdin.log"
    case "$input" in
      "ACL USERS")
        stubfail rd-pre
        stubreply rd-pre
        printf 'default\nadmin\nhealth\n'
        for f in "$S"/ruser_*; do [ ! -e "$f" ] || basename "${f#*ruser_}"; done ;;
      "ACL SETUSER "*)
        stubfail rd-setuser
        stubreply rd-setuser
        u="$(cut -d ' ' -f 3 <<<"$input")"
        printf '%s\n' "$input" > "$S/ruser_$u"
        echo OK ;;
      "ACL SAVE")
        stubfail rd-save
        stubreply rd-save
        echo "$(( $(cat "$S/saves" 2>/dev/null || echo 0) + 1 ))" > "$S/saves"
        echo OK ;;
      *) echo "stub: unknown redis command" >&2; exit 99 ;;
    esac
    exit 0 ;;
esac
exit 0
EOF

# ---- harness ----

fresh() {
  rm -rf "$STATE" "$SECRETS" "$JOBS" "$LOCKS" "$RESERVED"
  mkdir -p "$STATE" "$SECRETS" "$JOBS" "$LOCKS"
  "$REAL_CHMOD" 2710 "$SECRETS"
  "$REAL_CHMOD" 2710 "$JOBS"
  "$REAL_CHMOD" 1777 "$LOCKS"
  cp "$RESERVED_SRC" "$RESERVED"
  : > "$STATE/stdin.log"
  : > "$LOGGER_LOG"
  t_reset_calls
  export NEW_DB_SECRETS_ROOT="$SECRETS"
  export NEW_DB_JOB_SECRETS_ROOT="$JOBS"
  export NEW_DB_LOCK_DIR="$LOCKS"
  export NEW_DB_RESERVED_NAMES="$RESERVED"
  export NEW_DB_PG_CONTAINER="$PGC"
  export NEW_DB_REDIS_CONTAINER="$RDC"
  export NEW_DB_LOCK_WAIT=5
  unset NEW_DB_REDIS_CTR_ADMIN_FILE NEW_DB_EXEC_TIMEOUT
}

nd() { run_cmd bash "$script" "$@"; }
sv() { cat "$SECRETS/${2:-myapp}/$1" 2>/dev/null; }          # sv <file> [app]
docker_calls() { grep -c '^docker ' "$CALL_LOG" || true; }
# entries written to the data stores (anything past the read-only preflight queries)
mutations() { grep -E 'CREATE|ALTER|REVOKE|GRANT|ACL SETUSER|ACL SAVE' "$STATE/stdin.log" || true; }
# every file under the secrets root except the per-app lock files
secret_files() { find "$SECRETS" "$JOBS" -mindepth 1 ! -name '.*.lock' || true; }
jv() { cat "$JOBS/${2:-myapp}/$1" 2>/dev/null; }                # jv <file> [app]: a file in the job-secrets root
pre_secret() { # <file> <value> [app]
  local app="${3:-myapp}"
  mkdir -p "$SECRETS/$app"
  "$REAL_CHMOD" 750 "$SECRETS/$app"
  printf '%s' "$2" > "$SECRETS/$app/$1"
  "$REAL_CHMOD" 440 "$SECRETS/$app/$1"
}
count_named() { find "$1" -maxdepth 1 -name "$2" | wc -l; } # <dir> <glob>
valid_pw() { [[ "$1" =~ ^[A-Za-z0-9]{40}$ ]]; }

no_leaks() { # label: neither of the app's passwords is in the output, any argv or any log
  local pw f
  for f in db-password redis-password jobs-secret; do
    pw="$(sv "$f" "${2:-myapp}")"
    [ -n "$pw" ] || pw="$(jv "$f" "${2:-myapp}")"
    [ -n "$pw" ] || continue
    expect_out_lacks "$1 ($f not printed)" "$pw"
    if grep -qF -- "$pw" "$CALL_LOG"; then _fail "$1 ($f not in any argv)" "the password reached an argv"; else _pass; fi
    if grep -qF -- "$pw" "$LOGGER_LOG"; then _fail "$1 ($f not in the audit log)" "the password reached logger"; else _pass; fi
  done
}

