# ---- 5. failures in each phase: named, no temp file, a re-run converges ----

phase_case() { # <fail key> <phase name> <rc>
  local key="$1" name="$2" code="$3" first_db
  fresh
  echo "$code" > "$STATE/fail_$key"
  nd myapp
  expect_rc "phase $name rc $code fails" 1
  expect_out_has "phase $name rc $code is named" "phase '$name' failed (rc $code)"
  expect_eq "phase $name rc $code leaves no temp secret file" "$(find "$SECRETS" -name '.tmp*' | wc -l)" "0"
  if [ "$code" -eq 124 ]; then
    if grep -q "phase=$name end rc=124 .*timed out" "$LOGGER_LOG"; then _pass; else _fail "phase $name: the timeout is logged"; fi
  fi
  first_db="$(sv db-password)"
  rm -f "$STATE/fail_$key"
  nd myapp
  expect_rc "phase $name rc $code: re-run converges" 0
  if valid_pw "$(sv db-password)" && valid_pw "$(sv redis-password)"; then _pass; else _fail "phase $name rc $code: both secrets valid after the re-run"; fi
  [ -z "$first_db" ] || expect_eq "phase $name rc $code: db-password kept by the re-run" "$(sv db-password)" "$first_db"
  expect_file "phase $name rc $code: role exists after the re-run" "$STATE/role_myapp"
  expect_file "phase $name rc $code: database exists after the re-run" "$STATE/db_myapp"
  expect_file "phase $name rc $code: Redis user exists after the re-run" "$STATE/ruser_myapp"
  expect_eq "phase $name rc $code: schema revoke applied" "$(count_named "$STATE" 'schema_myapp')" "1"
  expect_eq "phase $name rc $code: the role was created exactly once" "$(cat "$STATE/role_creates")" "1"
  nd myapp
  expect_out_lacks "phase $name rc $code: the next run changes nothing" "changed:"
}
for code in 1 124; do
  phase_case pg-pre preflight-postgres "$code"
  phase_case rd-pre preflight-redis "$code"
  phase_case pg-role postgres-role "$code"
  phase_case pg-database postgres-database "$code"
  phase_case pg-grants postgres-grants "$code"
  phase_case pg-schema postgres-schema "$code"
  phase_case rd-setuser redis-acl-setuser "$code"
  phase_case rd-save redis-acl-save "$code"
done
