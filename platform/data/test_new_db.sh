#!/usr/bin/env bash
# Stub tests for new-db.sh. The docker stub is stateful (roles, databases, the Redis user rule and the connection limit
# live as files under $STATE) and records argv (CALL_LOG) and stdin (STATE/stdin.log, one "### psql db=<db>" or
# "### redis" header per call). The secrets root is a real temp directory with the setgid bit, the lock is the real
# flock, and the reserved-names list is a copy of the tracked registry file (comment lines included).
#
# FIXTURE SHAPES CONFIRMED BY THE LIVE RUN (platform/data/test_data_live.sh): the real psql preflight reply is
# "<roles>|<databases>" and redis-cli's non-tty replies are "OK" and the one-name-per-line ACL USERS list, exactly as
# stubbed here; the real new-db.sh ran against real servers there. The mutation cases stay.
#
# No real credentials: every password below is generated by new-db.sh into a scratch tree or is a fake fixture string.
# SC2016: stub bodies are single-quoted on purpose. SC1091: lib.sh is sourced by relative path.
# SC2154: $out and $rc are set by run_cmd in lib.sh. SC2034: some fixture variables are only read by sub-functions.
# shellcheck disable=SC1091,SC2016,SC2034,SC2154
set -uo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=../test/lib.sh
. "$here/../test/lib.sh"
